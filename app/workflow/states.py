"""Material-request lifecycle state machine.

Transitions are explicit; services add business guards on top (approval
exists, receipt exists, match result, etc.).  A legal transition alone is
never sufficient proof that a prerequisite business event happened —
the guard functions live in the module services and are tested.
"""
from __future__ import annotations

DRAFT = "DRAFT"
NEEDS_INFORMATION = "NEEDS_INFORMATION"
TECHNICALLY_VALIDATED = "TECHNICALLY_VALIDATED"
SOURCING = "SOURCING"
QUOTATIONS_RECEIVED = "QUOTATIONS_RECEIVED"
PENDING_GM_APPROVAL = "PENDING_GM_APPROVAL"
APPROVED = "APPROVED"
PO_ISSUED = "PO_ISSUED"
PAYMENT_PENDING = "PAYMENT_PENDING"
DELIVERY_PENDING = "DELIVERY_PENDING"
PARTIALLY_RECEIVED = "PARTIALLY_RECEIVED"
RECEIVED = "RECEIVED"
QC_HOLD = "QC_HOLD"
REJECTED = "REJECTED"
ACCEPTED = "ACCEPTED"
INVOICE_PENDING = "INVOICE_PENDING"
MATCHING = "MATCHING"
EXCEPTION = "EXCEPTION"
READY_TO_POST = "READY_TO_POST"
POSTED_TO_ERP = "POSTED_TO_ERP"
PAID_OR_RECONCILED = "PAID_OR_RECONCILED"
CLOSED = "CLOSED"

ALLOWED_TRANSITIONS: dict[str, set[str]] = {
    DRAFT: {NEEDS_INFORMATION, TECHNICALLY_VALIDATED},
    NEEDS_INFORMATION: {TECHNICALLY_VALIDATED, DRAFT},
    TECHNICALLY_VALIDATED: {SOURCING},
    SOURCING: {QUOTATIONS_RECEIVED},
    QUOTATIONS_RECEIVED: {PENDING_GM_APPROVAL, SOURCING},
    PENDING_GM_APPROVAL: {APPROVED, SOURCING},          # reject / modify -> re-source
    APPROVED: {PO_ISSUED},
    PO_ISSUED: {PAYMENT_PENDING, DELIVERY_PENDING, INVOICE_PENDING},
    PAYMENT_PENDING: {DELIVERY_PENDING, PARTIALLY_RECEIVED, RECEIVED, QC_HOLD, REJECTED, INVOICE_PENDING},
    DELIVERY_PENDING: {PARTIALLY_RECEIVED, RECEIVED, QC_HOLD, REJECTED},
    PARTIALLY_RECEIVED: {RECEIVED, QC_HOLD, REJECTED, DELIVERY_PENDING, INVOICE_PENDING},
    QC_HOLD: {ACCEPTED, REJECTED, DELIVERY_PENDING},
    REJECTED: {DELIVERY_PENDING, CLOSED, INVOICE_PENDING},
    ACCEPTED: {INVOICE_PENDING, CLOSED},
    RECEIVED: {INVOICE_PENDING},
    INVOICE_PENDING: {MATCHING},
    MATCHING: {READY_TO_POST, EXCEPTION},
    EXCEPTION: {READY_TO_POST, MATCHING, CLOSED},
    READY_TO_POST: {POSTED_TO_ERP},
    POSTED_TO_ERP: {PAID_OR_RECONCILED},
    PAID_OR_RECONCILED: {CLOSED},
    CLOSED: set(),
}


def assert_transition(current: str, target: str) -> None:
    if target not in ALLOWED_TRANSITIONS.get(current, set()):
        from app.shared.errors import InvalidTransition

        raise InvalidTransition(
            f"انتقال غير مسموح: {current} → {target}. "
            "لا يمكن القفز بين الحالات إلا عبر انتقال معرف."
        )
